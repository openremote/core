package org.openremote.model.asset;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonProperty;
import io.swagger.v3.oas.annotations.media.Schema;

/** An attribute of an {@link AttributeConfigurationDocument} as reported to the user. */
@Schema(description = "Name and type of an attribute within an imported document.")
public class AttributeConfigurationSummary {

  @Schema(description = "Attribute name.")
  protected String name;

  @Schema(description = "Value descriptor name of the attribute, e.g. number.")
  protected String type;

  @JsonCreator
  public AttributeConfigurationSummary(
      @JsonProperty("name") String name, @JsonProperty("type") String type) {
    this.name = name;
    this.type = type;
  }

  public String getName() {
    return name;
  }

  public String getType() {
    return type;
  }
}
